// Bundles public/ into the Function as base64 so Neon Functions serves the frontend and the
// API from one origin. Neon Functions only accepts a single bundled entry and has no static
// hosting, and the CSP in index.html is 'self' — so the assets have to travel with the code.
// Output is generated, git-ignored, and rebuilt by `npm run function:build` before every deploy.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync } from 'node:fs';
import { join, extname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const publicDir = join(root, 'public');
const outFile = join(root, 'src', 'function', 'assets.generated.mjs');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
};

function walk(dir, prefix = '') {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    const rel = posix.join(prefix, entry.name);
    if (entry.isDirectory()) out.push(...walk(abs, rel));
    else out.push({ abs, rel });
  }
  return out;
}

const files = walk(publicDir)
  .map(({ rel }) => {
    const type = TYPES[extname(rel).toLowerCase()];
    if (!type) throw new Error(`build-function: no MIME type for ${rel}`);
    const b64 = readFileSync(join(publicDir, rel)).toString('base64');
    return { path: `/${rel.split('/').map(encodeURIComponent).join('/')}`, type, b64 };
  })
  .sort((a, b) => a.path.localeCompare(b.path));

const body = files
  .map((f) => `  { path: ${JSON.stringify(f.path)}, type: ${JSON.stringify(f.type)}, b64: ${JSON.stringify(f.b64)} },`)
  .join('\n');

writeFileSync(
  outFile,
  `// Generated by scripts/build-function.mjs — do not edit.\nexport const assets = [\n${body}\n];\n`
);

const kb = (files.reduce((n, f) => n + f.b64.length, 0) / 1024).toFixed(1);
console.log(`[function] ${files.length} assets inlined (${kb} KiB base64) → src/function/assets.generated.mjs`);
